//------------------------------------------------------------------------------
// Module Name : apb_spi_controller
//
// Description :
// Top-level RTL module for an APB-based SPI controller.
//
// The APB slave interface is used to configure the SPI controller and to
// read/write the control, status, baud-rate, and data registers.
//
// The SPI functionality is divided into three main blocks:
//   1. SPI baud generator
//      - Generates the SPI clock
//      - Generates transmit and receive timing events
//
//   2. SPI shift register
//      - Serializes transmit data onto MOSI
//      - Samples serial data from MISO
//      - Supports MSB-first and LSB-first transfers
//
//   3. SPI slave control
//      - Controls SPI chip select (SS)
//      - Controls the start and completion of an SPI transfer
//
// The APB interface, baud generator, shift register, and SPI control logic
// communicate through the internal signals declared below.
//------------------------------------------------------------------------------

module apb_spi_controller(
    input        pclk,
    input        preset_n,
    input        pwrite,
    input        psel,
    input        penable,
    input        miso,
    input  [2:0] paddr,
    input  [7:0] pwdata,

    output       ss,
    output       sclk,
    output       spi_interupt_request,
    output       pready,
    output       pslverr,
    output       mosi,
    output [7:0] prdata
);

    //--------------------------------------------------------------------------
    // APB slave interface signals
    //
    // These signals carry SPI configuration, status, and data between the
    // APB register interface and the SPI functional blocks.
    //--------------------------------------------------------------------------

    wire       mstr_w;
    wire       lsbfe_w;
    wire       cpol_w;
    wire       cpha_w;
    wire       send_data_w;
    wire       spiswai_w;

    wire [2:0] spr_w;
    wire [2:0] sppr_w;
    wire [1:0] spi_mode_w;
    wire [7:0] mosi_data_w;


    //--------------------------------------------------------------------------
    // SPI shift register and baud generator signals
    //
    // The baud generator produces timing events used by the shift register
    // for SPI transmit and receive operations.
    //--------------------------------------------------------------------------

    wire        ss_w;
    wire        receive_data_w;

    wire        mosi_send_sclk0_w;
    wire        mosi_send_sclk_w;
    wire        miso_receive_sclk0_w;
    wire        miso_receive_sclk_w;

    wire [11:0] baudratedivisor_w;
    wire  [7:0] data_miso_w;


    //--------------------------------------------------------------------------
    // SPI control signals
    //--------------------------------------------------------------------------

    wire tip_w;


    //--------------------------------------------------------------------------
    // SPI slave select
    //
    // The internal SS signal generated by the SPI control block is connected
    // to the top-level SPI slave-select output.
    //--------------------------------------------------------------------------

    assign ss = ss_w;


    //--------------------------------------------------------------------------
    // APB Slave Interface
    //
    // Handles APB read/write transactions and stores the SPI configuration
    // registers. It also provides received SPI data and transfer status back
    // to the APB interface.
    //--------------------------------------------------------------------------

    apb_slave_interface spi_interface_dut (
        .pclk                    (pclk),
        .preset_n                (preset_n),
        .pwrite_i                (pwrite),
        .psel_i                  (psel),
        .paddr_i                 (paddr),
        .penable_i               (penable),
        .pwdata_i                (pwdata),

        .miso_data_i             (data_miso_w),
        .receive_data_i          (receive_data_w),
        .tip_i                   (tip_w),
        .ss_i                    (ss_w),

        .lsbfe_o                 (lsbfe_w),
        .mstr_o                  (mstr_w),
        .cpol_o                  (cpol_w),
        .cpha_o                  (cpha_w),
        .send_data_o             (send_data_w),
        .mosi_data_o             (mosi_data_w),
        .spr_o                   (spr_w),
        .sppr_o                  (sppr_w),
        .spiswai_o               (spiswai_w),
        .spi_mode_o              (spi_mode_w),

        .pready_o                (pready),
        .prdata_o                (prdata),
        .pslverr_o               (pslverr),
        .spi_interrupt_request_o (spi_interupt_request)
    );


    //--------------------------------------------------------------------------
    // SPI Baud Generator
    //
    // Generates the SPI clock (SCLK) based on the configured baud-rate
    // prescaler values. It also generates timing events used by the shift
    // register for transmit and receive operations.
    //--------------------------------------------------------------------------

    spi_baud_gen spi_baud_gen_dut (
        .pclk                    (pclk),
        .preset_n                (preset_n),
        .cpol_i                  (cpol_w),
        .cpha_i                  (cpha_w),
        .spiswai_i               (spiswai_w),
        .spi_mode_i              (spi_mode_w),
        .ss_i                    (ss_w),
        .spr_i                   (spr_w),
        .sppr_i                  (sppr_w),

        .sclk_o                  (sclk),

        .mosi_send_sclk0_o       (mosi_send_sclk0_w),
        .mosi_send_sclk_o        (mosi_send_sclk_w),
        .miso_receive_sclk_o     (miso_receive_sclk_w),
        .miso_receive_sclk0_o    (miso_receive_sclk0_w),
        .baudratedivisor         (baudratedivisor_w)
    );


    //--------------------------------------------------------------------------
    // SPI Shift Register
    //
    // Performs parallel-to-serial conversion for transmit data and
    // serial-to-parallel conversion for received MISO data.
    //
    // The shift operation is controlled by the timing events generated by
    // the SPI baud generator.
    //--------------------------------------------------------------------------

    spi_shift_register spi_shift_register_dut (
        .pclk                    (pclk),
        .preset_n                (preset_n),
        .cpol_i                  (cpol_w),
        .cpha_i                  (cpha_w),
        .lsbfe_i                 (lsbfe_w),

        .mosi_send_sclk0         (mosi_send_sclk0_w),
        .mosi_send_sclk          (mosi_send_sclk_w),
        .miso_receive_sclk0      (miso_receive_sclk0_w),
        .miso_receive_sclk       (miso_receive_sclk_w),

        .send_data_i             (send_data_w),
        .receive_data_i          (receive_data_w),
        .data_mosi_i             (mosi_data_w),

        .miso_i                  (miso),
        .ss_i                    (ss_w),

        .mosi_o                  (mosi),
        .data_miso_o             (data_miso_w)
    );


    //--------------------------------------------------------------------------
    // SPI Slave Control
    //
    // Controls the SPI transaction using the configured master settings and
    // baud-rate divisor. Generates the slave-select signal and indicates
    // when an SPI transfer is in progress or completed.
    //--------------------------------------------------------------------------

    spi_slave_control_select spi_slave_control_select_dut (
        .pclk                    (pclk),
        .preset_n                (preset_n),
        .mstr_i                  (mstr_w),
        .spiswai_i               (spiswai_w),
        .spi_mode_i              (spi_mode_w),
        .baudratedivisor_i       (baudratedivisor_w),
        .send_data_i             (send_data_w),

        .receive_data_o          (receive_data_w),
        .ss_o                    (ss_w),
        .tip_o                   (tip_w)
    );

endmodule